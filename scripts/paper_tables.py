def hyper_table(A_full, A_orig):
    lines = ["\\begin{table}[t]", "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
             "\\TabCaption{tab:hyper}{Settings chosen on the validation split}{One row per split. $\\lambda$: "
             "\\kaam{} smoothness weight; $C$: inverse L2 strength of logistic regression; MLP: hidden layers and "
             "learning rate; LightGBM: leaves and minimum leaf size. Mean best epoch over the five seeds in "
             "parentheses for \\kaam{} and the MLP.}",
             "\\begin{tabular}{@{}llllll@{}}", "\\toprule",
             "Data & Split & $\\lambda$ (epoch) & $C$ & MLP (epoch) & LightGBM \\\\", "\\midrule"]
    for ds, A in [("full", A_full), ("original", A_orig)]:
        se = A["selection"]
        if se is None:
            continue
        for (proto, split), g in se.groupby(["protocol", "split"], sort=False):
            def ch(m):
                r = g[g.model == m]
                return (json.loads(r.iloc[0]["chosen"]), r.iloc[0]) if len(r) else (None, None)
            k, kr = ch("kaam")
            c, _ = ch("lr")
            mlp, mr = ch("mlp")
            lg, _ = ch("lgbm")
            lam = "--" if k is None else (("0" if k["lambda"] == 0 else f"$10^{{{int(round(math.log10(k['lambda'])))}}}$")
                                          + f" ({kr['mean_best_epoch']:.0f})")
            cc = "--" if c is None else f"{c['C']:g}"
            mm = "--" if mlp is None else f"({','.join(str(h) for h in mlp['hidden'])}), {mlp['lr']:g} ({mr['mean_best_epoch']:.0f})"
            ll = "--" if lg is None else f"{lg['num_leaves']}, {lg['min_child_samples']}"
            lines.append(f"{'Full' if ds == 'full' else 'Original'} & {proto} {split} & {lam} & {cc} & {mm} & {ll} \\\\")
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines += ["\\end{tabular}", "\\TabNotes", "\\end{table}", ""]
    write_table("hyper", "\n".join(lines))


