def load_analysis(ds):
    a = RES / "analysis" / ds
    out = {}
    for name in ["summary", "comparisons", "chance_tests", "model_ci", "fold_auc", "mechanism", "reliability",
                 "selection", "split_facts", "metrics_runs"]:
        p = a / f"{name}.csv"
        out[name] = pd.read_csv(p) if p.exists() else None
        out[name + "_path"] = p
    return out


def result_numbers(ds, A):
    dk = "full" if ds == "full" else "orig"
    summ, comp, mci = A["summary"], A["comparisons"], A["model_ci"]
    for pid, (proto, sub) in FAM.items():
        for m in MODELS:
            mk = MKEY[m]
            base = f"{dk}.{pid}.{mk}"
            try:
                r = row_of(mci, protocol=proto, subset=sub, model=m)
            except KeyError:
                continue
            fld = dict(protocol=proto, subset=sub, model=m)
            N.add(f"{base}.auc", f3(r["auc"]), r["auc"], rp(A["model_ci_path"]), field_of("auc", **fld))
            N.add(f"{base}.ci", fci(r["ci_low"], r["ci_high"]), [r["ci_low"], r["ci_high"]], rp(A["model_ci_path"]),
                  field_of("ci_low,ci_high", **fld))
            s = row_of(summ, protocol=proto, subset=sub, model=m)
            for col, key, d in [("pr_auc", "prauc", 3), ("brier", "brier", 3), ("ece", "ece", 3),
                                ("set_std", "setstd", 3), ("seed_std", "seedstd", 4)]:
                if not pd.isna(s[col]):
                    N.add(f"{base}.{key}", f3(s[col], d), s[col], rp(A["summary_path"]), field_of(col, **fld))
            N.add(f"{dk}.{pid}.ntest", fint(s["n_test"]), s["n_test"], rp(A["summary_path"]),
                  field_of("n_test", **fld))
            N.add(f"{dk}.{pid}.rate", fpct(s["failure_rate"]), s["failure_rate"], rp(A["summary_path"]),
                  field_of("failure_rate", **fld))
            if m != "kaam":
                try:
                    c = row_of(comp, protocol=proto, subset=sub, model=m)
                except KeyError:
                    continue
                N.add(f"{base}.diff", fsig(c["diff"]), c["diff"], rp(A["comparisons_path"]), field_of("diff", **fld))
                N.add(f"{base}.absdiff", f3(abs(c["diff"])), abs(c["diff"]), rp(A["comparisons_path"]),
                      "derived: |diff|")
                N.add(f"{base}.dci", fci(c["ci_low"], c["ci_high"]), [c["ci_low"], c["ci_high"]],
                      rp(A["comparisons_path"]), field_of("ci_low,ci_high", **fld))
                N.add(f"{base}.p", fp(c["p_holm"]), c["p_holm"], rp(A["comparisons_path"]), field_of("p_holm", **fld))
                N.add(f"{base}.sig", sigword(c["p_holm"]), c["p_holm"], rp(A["comparisons_path"]),
                      field_of("p_holm", **fld))
    # every model on the canonical random split alone (includes the full-trace EBM, fitted only there)
    mr = A["metrics_runs"]
    if mr is not None and len(mr):
        can = mr[(mr.protocol == "random") & (mr.subset == "all") & (mr.split == "s42")]
        for m, g in can.groupby("model"):
            N.add(f"{dk}.s42.{MKEY[m]}.auc", f3(g["roc_auc"].mean()), g["roc_auc"].mean(), rp(A["metrics_runs_path"]),
                  f"derived: mean roc_auc over seeds, random s42, {m}")
    # AUC drop from random to grouped and to new users, per model
    for m in MODELS:
        mk = MKEY[m]
        try:
            r0 = row_of(mci, protocol="random", subset="all", model=m)["auc"]
            for pid in ["grouped", "timenew", "timeknown", "louoa", "louob", "time"]:
                proto, sub = FAM[pid]
                r1 = row_of(mci, protocol=proto, subset=sub, model=m)["auc"]
                N.add(f"{dk}.drop.{pid}.{mk}", fsig(r1 - r0), r1 - r0, rp(A["model_ci_path"]),
                      f"derived: auc({pid}) - auc(random)")
        except KeyError:
            pass
    # ranges over models
    for pid, (proto, sub) in FAM.items():
        sel = mci[(mci.protocol == proto) & (mci.subset == sub)]
        if len(sel):
            N.add(f"{dk}.{pid}.minauc", f3(sel["auc"].min()), sel["auc"].min(), rp(A["model_ci_path"]),
                  f"derived: min auc over models ({pid})")
            N.add(f"{dk}.{pid}.maxauc", f3(sel["auc"].max()), sel["auc"].max(), rp(A["model_ci_path"]),
                  f"derived: max auc over models ({pid})")
            for col, key in [("ece", "ece"), ("brier", "brier")]:
                ss = summ[(summ.protocol == proto) & (summ.subset == sub)]
                N.add(f"{dk}.{pid}.min{key}", f3(ss[col].min()), ss[col].min(), rp(A["summary_path"]),
                      f"derived: min {col} over models ({pid})")
                N.add(f"{dk}.{pid}.max{key}", f3(ss[col].max()), ss[col].max(), rp(A["summary_path"]),
                      f"derived: max {col} over models ({pid})")

    # chance tests (grouped)
    ch = A["chance_tests"]
    if ch is not None and len(ch):
        for _, r in ch.iterrows():
            mk = MKEY[r["model"]]
            fld = dict(model=r["model"])
            N.add(f"{dk}.chance.{mk}.p", fp(r["p_holm"]), r["p_holm"], rp(A["chance_tests_path"]),
                  field_of("p_holm", **fld))
            N.add(f"{dk}.chance.{mk}.sig", sigword(r["p_holm"]), r["p_holm"], rp(A["chance_tests_path"]),
                  field_of("p_holm", **fld))
        below = ch[ch["ci_high"] < 0.5]
        N.add(f"{dk}.chance.nbelow", fword(len(below)), len(below), rp(A["chance_tests_path"]),
              "derived: models whose interval lies below 0.5")
        nsig = int((ch["p_holm"] < 0.05).sum())
        N.add(f"{dk}.chance.nsig", fword(nsig), nsig, rp(A["chance_tests_path"]), "derived: models with p_holm < 0.05")
        N.add(f"{dk}.chance.nmodels", fword(len(ch)), len(ch), rp(A["chance_tests_path"]), "derived: rows")
    # folds
    fa = A["fold_auc"]
