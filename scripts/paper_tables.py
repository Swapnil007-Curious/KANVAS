# ----------------------------------------------------------------------------- formatting
def f3(x, d=3):
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def fsig(x, d=3):
    """Signed number with a typeset minus sign."""
    s = f"{abs(x):.{d}f}"
    if float(s) == 0:
        return s
    return ("$-$" if x < 0 else "+") + s


def fneg(x, d=3):
    """Number with a typeset minus sign and no plus sign."""
    s = f"{abs(x):.{d}f}"
    return ("$-$" + s) if x < 0 and float(s) != 0 else s


def fci(lo, hi, d=3):
    return f"[{fneg(lo, d)}, {fneg(hi, d)}]"


def fint(x):
    return f"{int(round(x)):,}"


def fpct(x, d=1):
    return f"{100 * x:.{d}f}\\%"


def fp(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def fsci(x, digits=1):
    """Scientific notation in math mode, e.g. $3\\times10^{-16}$."""
    if x == 0:
        return "0"
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10 ** e
    ms = f"{m:.{digits}f}"
    if float(ms) == 10:
        e += 1
        ms = f"{1:.{digits}f}"
    return f"${ms}\\times10^{{{e}}}$"


WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]


def fword(n):
    """Small counts as words, as the text uses them; larger counts as numbers."""
    n = int(n)
    return WORDS[n] if 0 <= n <= 10 else fint(n)


def sigword(p_holm):
    return "significant" if p_holm < 0.05 else "not significant"


class Numbers:
    def __init__(self):
        self.items = {}

    def add(self, key, text, raw, source, field):
        if key in self.items and self.items[key]["text"] != text:
            raise ValueError(f"macro {key} defined twice with different text")
        if not re.fullmatch(r"[A-Za-z0-9.]+", key):
            raise ValueError(f"bad macro key {key}")
        if isinstance(raw, (np.floating, np.integer)):
            raw = raw.item()
        if isinstance(raw, np.bool_):
            raw = bool(raw)
        self.items[key] = {"text": text, "raw": raw, "source": source, "field": field}

    def write(self):
        TABLES.mkdir(parents=True, exist_ok=True)
        DATA.mkdir(parents=True, exist_ok=True)
        lines = ["% Generated by scripts/paper_tables.py. Do not edit.",
                 "% Each number quoted in the paper is \\V{key}; sources: paper/data/macro_sources.json."]
        for k in sorted(self.items):
            lines.append(f"\\expandafter\\def\\csname v@{k}\\endcsname{{{self.items[k]['text']}}}")
        (TABLES / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
        (DATA / "macro_sources.json").write_text(json.dumps(self.items, indent=1, default=float), encoding="utf-8")


N = Numbers()


def rp(p):
    """Source path string for a file under the result root."""
    return "results/" + Path(p).relative_to(RES).as_posix()


def write_table(name, body):
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / f"{name}.tex").write_text("% Generated by scripts/paper_tables.py. Do not edit.\n" + body,
                                        encoding="utf-8")


def tex_escape(s):
    return s.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def row_of(df, **kv):
    m = np.ones(len(df), bool)
    for k, v in kv.items():
        m &= (df[k].astype(str) == str(v)).to_numpy()
    sub = df[m]
    if len(sub) != 1:
        raise KeyError(f"{len(sub)} rows for {kv}")
    return sub.iloc[0]


def field_of(col, **kv):
    return ";".join(f"{k}={v}" for k, v in kv.items()) + ":" + col


